// ─── Helpers ─────────────────────────────────────────────────────────────────

export function getPartBySku(sku: string): Part | undefined {
  return mockParts.find((p) => p.sku === sku);
}

export function getFeaturedParts(): Part[] {
  return mockParts.filter((p) => p.isFeatured);
}

export function getPartsByFitment(year: number, make: string, model: string): Part[] {
  return mockParts.filter((p) =>
    p.fitment.some(
      (f) =>
        f.year === year &&
        f.make.toLowerCase() === make.toLowerCase() &&
        f.model.toLowerCase() === model.toLowerCase()
    )
  );
}

